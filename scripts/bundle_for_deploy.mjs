// Genera versiones "inline" de cada Edge Function concatenando los helpers de
// _shared, para minimizar complicaciones de multi-file en deploy_edge_function.
// Output: supabase/functions/.bundled/<fn>/index.ts (un solo archivo).
//
// Uso: node scripts/bundle_for_deploy.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(process.cwd(), 'supabase', 'functions');
const OUT_ROOT = path.join(ROOT, '.bundled');

const SHARED = {
  cors:      fs.readFileSync(path.join(ROOT, '_shared', 'cors.ts'), 'utf8'),
  resend:    fs.readFileSync(path.join(ROOT, '_shared', 'resend.ts'), 'utf8'),
  templates: fs.readFileSync(path.join(ROOT, '_shared', 'templates.ts'), 'utf8'),
  stripe:    fs.readFileSync(path.join(ROOT, '_shared', 'stripe.ts'), 'utf8'),
};

// Extrae exports (tanto `export function` como `export const/class/interface`).
// Devuelve el SOURCE con los `export` kw removidos y sin duplicar globals como
// import/module.
function stripExports(src) {
  return src.replace(/^export\s+/gm, '');
}

// Extrae imports externos (https URLs + esm.sh). Devuelve set de líneas únicas.
function extractExternalImports(src) {
  const lines = src.split(/\r?\n/);
  const out = new Set();
  for (const l of lines) {
    const m = l.match(/^\s*import\s+.*from\s+["']https?:\/\/[^"']+["'];?\s*$/);
    if (m) out.add(l.trim());
  }
  return out;
}

// Remueve líneas `import ... from "../_shared/..."` y las URL imports (las
// reinsertaremos al principio deduplicadas).
function stripLocalAndUrlImports(src) {
  return src.split(/\r?\n/).filter((l) => {
    if (/^\s*import\s+.*from\s+["']\.\.\/_shared\/[^"']+["'];?\s*$/.test(l)) return false;
    if (/^\s*import\s+.*from\s+["']https?:\/\/[^"']+["'];?\s*$/.test(l)) return false;
    return true;
  }).join('\n');
}

function bundleFn(fnName, sharedKeys) {
  const indexPath = path.join(ROOT, fnName, 'index.ts');
  if (!fs.existsSync(indexPath)) throw new Error('no existe ' + indexPath);
  const indexSrc = fs.readFileSync(indexPath, 'utf8');

  // 1. Dedupe external imports (fn index + shared used)
  const externals = new Set();
  for (const k of sharedKeys) {
    extractExternalImports(SHARED[k]).forEach((i) => externals.add(i));
  }
  extractExternalImports(indexSrc).forEach((i) => externals.add(i));

  // 2. Strip local imports + url imports from each (re-added at top)
  const sharedStripped = sharedKeys
    .map((k) => `// ---- inlined from _shared/${k}.ts ----\n${stripExports(stripLocalAndUrlImports(SHARED[k]))}`)
    .join('\n\n');

  const indexStripped = stripLocalAndUrlImports(indexSrc);

  const bundled = [
    '// AUTO-GENERATED by scripts/bundle_for_deploy.mjs',
    '// Do not edit directly - edit the source files and rerun the script.',
    '',
    ...externals,
    '',
    sharedStripped,
    '',
    '// ---- main function body ----',
    indexStripped,
  ].join('\n');

  const outDir = path.join(OUT_ROOT, fnName);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.ts'), bundled, 'utf8');
  return { fnName, bytes: Buffer.byteLength(bundled, 'utf8') };
}

const PLAN = [
  { fn: 'send-email',              shared: ['cors', 'resend', 'templates'] },
  { fn: 'cron-recordatorios-24h',  shared: ['cors', 'resend', 'templates'] },
  { fn: 'stripe-checkout',         shared: ['cors', 'stripe'] },
  { fn: 'stripe-webhook',          shared: ['cors', 'stripe'] },
  { fn: 'cancel-cita',             shared: ['cors', 'stripe'] },
  { fn: 'assign-recurso',          shared: ['cors'] },
  { fn: 'resend-webhook',          shared: [] },
];

fs.rmSync(OUT_ROOT, { recursive: true, force: true });
for (const p of PLAN) {
  const r = bundleFn(p.fn, p.shared);
  console.log(`${r.fnName}: ${r.bytes} bytes`);
}
